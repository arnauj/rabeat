const img = (id, w = 800) =>
  `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=${w}&q=70`

// Horario semanal: índice 0 = domingo … 6 = sábado.
// Un tramo que termina después de medianoche se escribe con hora de cierre menor
// que la de apertura (p. ej. ['19:00', '01:00']).
const week = (ranges, closedDays = []) =>
  Array.from({ length: 7 }, (_, day) => (closedDays.includes(day) ? [] : ranges))

const dish = (id, name, description, price, photo, allergens, info = {}) => ({
  id,
  name,
  description,
  price,
  image: img(photo, 600),
  allergens,
  kcal: info.kcal,
  portion: info.portion,
  prep: info.prep,
  tags: info.tags ?? [],
  orders: info.orders ?? 0,
})

